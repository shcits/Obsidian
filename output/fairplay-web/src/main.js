import './styles.css';
import {createPassportScene} from './scene.js';
import {initMotion} from './motion.js';
import {initBooking} from './booking.js';
import {createHeroReveal} from './hero-reveal.js';
import {initCollection} from './collection.js';
import {createVictoryImage} from './victory-image.js';
import './news-gallery.css';
import './newspaper.css';
import './publication.css';
import './reading.css';
import './newspaper-overview.css';
import './newspaper-portrait.css';
import './site-menu.css';
import './interaction-refinements.css';
import {initSiteMenu} from './site-menu.js';
const siteMenu=initSiteMenu();
const reduced=matchMedia('(prefers-reduced-motion: reduce)').matches;
if(reduced)document.body.classList.add('is-reduced');
const landing=document.querySelector('#contenido'),reservation=document.querySelector('#reservation-view');
let experience,booking,victory;
const heroReveal=createHeroReveal({reduced});
const collection=initCollection();
const motion=initMotion({reduced,collection,onFrame:(progress,time,celebrationProgress,handoff)=>{heroReveal.render();experience?.render(progress,time,handoff);victory?.render(celebrationProgress)}});
victory=createVictoryImage({reduced,onLayout:()=>motion.refresh()});
function navigate(hash,{immediate=false}={}){const wasReservation=!reservation.hidden;if(wasReservation)booking?.save();if(location.hash!==hash)history.pushState(null,'',hash);const isReservation=['#entradas','#revision','#confirmacion'].includes(hash);landing.hidden=isReservation;reservation.hidden=!isReservation;motion.pause(isReservation);if(isReservation){window.scrollTo(0,0);booking.show(hash)}else{motion.refresh();const target=hash==='#recompensas'?motion.rewardsStart():hash==='#contexto'&&document.body.classList.contains('victory-static')?document.querySelector('.sportswashing-panel'):(document.querySelector(hash||'#inicio')||landing);motion.scrollTo(target,immediate||wasReservation)}document.querySelectorAll('[data-nav]').forEach(link=>{if(isReservation&&link.dataset.nav==='tickets')link.setAttribute('aria-current','location');else if(isReservation)link.removeAttribute('aria-current')})}
booking=initBooking({navigate});
const links=event=>{const anchor=event.target.closest('a[href^="#"]');if(!anchor||event.defaultPrevented||event.button!==0||event.metaKey||event.ctrlKey||event.shiftKey||event.altKey)return;event.preventDefault();navigate(anchor.getAttribute('href'))};
document.addEventListener('click',links);
const historyChange=()=>navigate(location.hash||'#inicio',{immediate:true});addEventListener('popstate',historyChange);addEventListener('hashchange',historyChange);
const sceneReady=createPassportScene({reduced}).then(value=>{experience=value;motion.refresh()}).catch(error=>{console.error(error);document.body.classList.add('no-webgl');document.querySelector('#model-loading').textContent='El pasaporte físico te espera en el evento.';motion.refresh()});
if(location.hash)Promise.all([document.fonts.ready,sceneReady]).then(()=>requestAnimationFrame(historyChange));
addEventListener('pagehide',()=>{siteMenu.dispose();motion.dispose();booking.dispose();experience?.dispose();victory.dispose();heroReveal.dispose();collection.dispose();document.removeEventListener('click',links);removeEventListener('popstate',historyChange);removeEventListener('hashchange',historyChange)},{once:true});
